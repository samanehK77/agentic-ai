"""The one place that writes audit events.

Every write uses its OWN database session and transaction, never the request's: events must survive when the answer
transaction rolls back or the request fails. Writes are FAIL-OPEN: a rejected payload or a database error is logged as a
safe one-line message (event type, error class, never a value), counted in `failures`, and the user's request goes on.
The one exception is student feedback, which is the user's own action and reports a 503 when it cannot be stored.

The counter lives in this process and starts again at zero on a restart (documented in docs/OBSERVABILITY.md)."""
import hashlib
import json
import logging
import re
import threading
import time
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from uuid import UUID

from sqlalchemy.engine import Engine
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session

from app.audit.events import RejectedMetadata, check_metadata
from app.errors import ApiError
from app.repositories import audit as repo

logger = logging.getLogger("mindevidence.audit")

CONFIG_CACHE_SECONDS = 60


@dataclass
class Event:
    """One event to write. `metadata` is checked against the catalogue before anything is stored."""

    event_type: str
    outcome: str = "ok"
    metadata: dict = field(default_factory=dict)
    latency_ms: int | None = None
    error_code: str | None = None
    occurred_at: datetime | None = None


def new_correlation_id() -> UUID:
    """One per question or action, generated by the server (never the client's request id)."""
    return uuid.uuid4()


def safe_code(value: str | None) -> str | None:
    """A name made safe for the metadata rules (letters, digits and _ . : / - only, at most 120 characters)."""
    return None if value is None else re.sub(r"[^A-Za-z0-9_.:/-]", "_", value)[:120]


def short_hash(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:12]


class AuditService:
    def __init__(self, engine: Engine):
        self.engine = engine
        self._failures = 0
        self._lock = threading.Lock()
        self._chunking: tuple[float, str | None] | None = None

    @property
    def failures(self) -> int:
        return self._failures

    def _count_failure(self) -> None:
        with self._lock:
            self._failures += 1

    # ---------------------------------------------------------------- writing

    def _rows(self, events: list[Event], correlation_id: UUID, user_id: UUID | None, session_id: UUID | None,
              request_id: str | None) -> list[dict]:
        rows = []
        for event in events:
            try:
                metadata = check_metadata(event.event_type, event.metadata)
            except RejectedMetadata as error:
                # Key names and error kinds only: the rejected value is never logged.
                logger.warning("audit_event_rejected type=%s problems=%s", event.event_type, error)
                self._count_failure()
                continue
            rows.append({
                "occurred_at": event.occurred_at or datetime.now(timezone.utc), "correlation_id": correlation_id, "request_id": request_id,
                "user_id": user_id, "session_id": session_id, "event_type": event.event_type, "outcome": event.outcome,
                "error_code": event.error_code, "latency_ms": event.latency_ms, "seq": len(rows), "metadata": metadata})
        return rows

    def record_many(self, events: list[Event], *, correlation_id: UUID, user_id: UUID | None = None,
                    session_id: UUID | None = None, request_id: str | None = None, first_seq: int = 0) -> bool:
        """Writes the events in ONE audit transaction (in the given order). Returns False when the write failed."""
        try:
            rows = self._rows(events, correlation_id, user_id, session_id, request_id)
            for row in rows:
                row["seq"] += first_seq
            if not rows:
                return True
            with Session(self.engine) as db:
                repo.insert_many(db, rows)
                db.commit()
            return True
        except Exception as error:  # fail-open: whatever went wrong must not break the request
            logger.error("audit_write_failed types=%s error=%s", ",".join(e.event_type for e in events)[:200], type(error).__name__)
            self._count_failure()
            return False

    def record(self, event_type: str, outcome: str = "ok", *, correlation_id: UUID | None = None, user_id: UUID | None = None,
               session_id: UUID | None = None, request_id: str | None = None, error_code: str | None = None,
               latency_ms: int | None = None, metadata: dict | None = None) -> bool:
        return self.record_many(
            [Event(event_type, outcome, metadata or {}, latency_ms, error_code)],
            correlation_id=correlation_id or new_correlation_id(), user_id=user_id, session_id=session_id, request_id=request_id)

    def record_feedback(self, *, user_id: UUID, session_id: UUID, request_id: str | None, message_id: str, rating: str,
                        reason: str | None) -> tuple[dict, bool]:
        """Stores the first feedback of this user on this message. Returns (metadata, created). Not fail-open."""
        try:
            metadata = check_metadata("feedback_submitted", {"message_id": message_id, "rating": rating, "reason": reason})
        except RejectedMetadata:
            raise ApiError(422, "validation_error", "The feedback is not valid.") from None
        try:
            with Session(self.engine) as db:
                repo.lock_feedback(db, message_id)  # two quick clicks cannot both insert
                existing = repo.find_feedback(db, user_id, session_id, message_id)
                if existing:
                    return existing["metadata"], False
                correlation = repo.correlation_of_answer(db, session_id, message_id) or new_correlation_id()
                rows = self._rows([Event("feedback_submitted", "ok", metadata)], correlation, user_id, session_id, request_id)
                repo.insert_many(db, rows)
                db.commit()
            return metadata, True
        except SQLAlchemyError as error:
            logger.error("audit_write_failed types=feedback_submitted error=%s", type(error).__name__)
            self._count_failure()
            raise ApiError(503, "service_unavailable", "The feedback could not be saved. Please try again.") from None

    # ---------------------------------------------------------------- configuration of an answer

    def _chunking_version(self) -> str | None:
        now = time.monotonic()
        if self._chunking and now - self._chunking[0] < CONFIG_CACHE_SECONDS:
            return self._chunking[1]
        try:
            with Session(self.engine) as db:
                value = repo.chunking_version(db)
        except Exception as error:
            logger.warning("audit_config_unavailable error=%s", type(error).__name__)
            value = None
        self._chunking = (now, value)
        return value

    def config_snapshot(self, settings, embedder_provider) -> dict:
        """The non-sensitive settings that shaped an answer, with a fingerprint over them. Embedding and chunking
        versions are stored as short hashes (the readable names contain characters the metadata rules do not allow)."""
        llm = settings.llm
        embedding_full = embedder_provider.fingerprint
        chunking_full = self._chunking_version()
        from app.llm.prompt import PROMPT_VERSION
        from app.retrieval.embedder import MODEL_NAME

        parts = {
            "model": llm.model, "prompt_version": PROMPT_VERSION, "retrieval_threshold": settings.retrieval_min_similarity,
            "top_k": settings.answer_top_k, "embedding": embedding_full, "chunking": chunking_full}
        snapshot = {
            "config_fingerprint": short_hash(json.dumps(parts, sort_keys=True)), "model": safe_code(llm.model), "prompt_version": PROMPT_VERSION,
            "retrieval_threshold": settings.retrieval_min_similarity, "top_k": settings.answer_top_k,
            "embedding_model": MODEL_NAME, "embedding_fingerprint": short_hash(embedding_full),
            "chunking_version": short_hash(chunking_full) if chunking_full else "unknown"}
        return snapshot
