"""API shapes of the audit log (Batch 09). Metadata only: no question, patient or chunk text, prompts, answers, tokens
or e-mail addresses exist in an audit event, so none can appear here."""
from datetime import date, datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.audit.events import FEEDBACK_REASONS
from db.models import VOCAB

EventType = Literal[*VOCAB["audit_event_type"]]
Outcome = Literal[*VOCAB["audit_outcome"]]


class AuditEventOut(BaseModel):
    event_id: UUID
    event_type: EventType
    outcome: Outcome
    occurred_at: datetime
    latency_ms: int | None = None
    error_code: str | None = None
    seq: int = 0
    metadata: dict = Field(description="Only the keys allowed for this event type (docs/OBSERVABILITY.md).")


class TimelineConfig(BaseModel):
    config_fingerprint: str | None = None
    model: str | None = None
    prompt_version: str | None = None
    retrieval_threshold: float | None = None
    top_k: int | None = None
    embedding_model: str | None = None
    embedding_fingerprint: str | None = None
    chunking_version: str | None = None


class TimelineGroup(BaseModel):
    correlation_id: UUID = Field(description="One per question or action, generated by the server.")
    kind: Literal["question", "action"]
    outcome: str = Field(description="Questions: answered, no_evidence, unsupported, crisis, replayed, error, running, "
                                     "interrupted. Actions: ok or denied.")
    error_code: str | None = None
    total_latency_ms: int | None = Field(default=None, description="Total answer time of a finished question.")
    started_at: datetime
    config: TimelineConfig | None = Field(default=None, description="Settings that shaped the answer (from question_submitted).")
    events: list[AuditEventOut]


class TimelinePage(BaseModel):
    items: list[TimelineGroup]
    total: int = Field(description="Number of groups (questions and actions) of this session.")
    limit: int
    offset: int


class AdminAuditEventOut(AuditEventOut):
    correlation_id: UUID
    request_id: str | None = None
    user_id: UUID | None = None
    session_id: UUID | None = None


class SummaryDay(BaseModel):
    day: date
    event_type: EventType
    count: int


class AuditSummary(BaseModel):
    date_from: datetime | None = None
    date_to: datetime | None = None
    per_day: list[SummaryDay]
    answers_returned: int = Field(description="answer_returned events with outcome ok (all results, replays excluded).")
    pipeline_errors: int
    error_rate: float | None = Field(description="pipeline_error / (answers returned + pipeline_error); null with no data.")
    no_evidence_rate: float | None = Field(description="Share of returned answers whose result was no_evidence.")
    answer_latency_p50_ms: float | None = None
    answer_latency_p95_ms: float | None = None
    audit_write_failures: int = Field(description="Audit writes that failed or were rejected since this server process "
                                                  "started (the counter restarts at zero).")


class FeedbackCreate(BaseModel):
    model_config = ConfigDict(extra="forbid", json_schema_extra={"examples": [{"rating": "helpful", "reason": "clear"}]})

    rating: Literal["helpful", "not_helpful"]
    reason: Literal[*FEEDBACK_REASONS] | None = Field(default=None, description="One fixed code; there is no free text.")


class FeedbackOut(BaseModel):
    message_id: UUID
    rating: Literal["helpful", "not_helpful"]
    reason: str | None = None
    already_recorded: bool = Field(description="True when an earlier feedback on this message was kept (the first one stands).")
